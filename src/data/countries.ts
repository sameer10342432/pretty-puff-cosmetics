export const POPULAR_COUNTRIES: CountryInfo[] = COUNTRIES.filter(c => c.popular);

export const DEFAULT_COUNTRY: CountryInfo = COUNTRIES.find(c => c.code === 'US') || COUNTRIES[0];

export function getCountryByCode(code: string): CountryInfo {
  if (!code) return DEFAULT_COUNTRY;
  const upper = code.trim().toUpperCase();
  return COUNTRIES.find(c => c.code === upper) || DEFAULT_COUNTRY;
}

export function searchCountries(query: string): CountryInfo[] {
  if (!query || !query.trim()) return COUNTRIES;
  const q = query.toLowerCase().trim();
  return COUNTRIES.filter(c => 
    c.name.toLowerCase().includes(q) ||
    c.code.toLowerCase().includes(q) ||
    c.currency.toLowerCase().includes(q) ||
    c.dialCode.includes(q)
  );
}
